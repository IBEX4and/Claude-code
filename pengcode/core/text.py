ADVANCE = 1.35  # largura de avanço entre caracteres, em unidades de glifo


def text_paths(
    text: str,
    x: float = 0.0,
    y: float = 0.0,
    height: float = 4.0,
    spacing: float = 0.0,
    **path_kwargs,
) -> list[Path]:
    """Escreve `text` com a base da linha em (x, y). `height` em mm."""
    scale = height / 2.0
    step = ADVANCE * scale + spacing
    out: list[Path] = []
    cursor = float(x)
    for char in text.upper():
        for stroke in GLYPHS.get(char, []):
            pts = np.asarray(stroke, dtype=float) * scale + np.array([cursor, y])
            out.append(Path(pts, **path_kwargs))
        cursor += step
    return out


def text_width(text: str, height: float = 4.0, spacing: float = 0.0) -> float:
    if not text:
        return 0.0
    return len(text) * (ADVANCE * height / 2.0 + spacing) - spacing
